-- Reference tables (configurable by the admin)
CREATE TABLE goal (
    code        VARCHAR(30) PRIMARY KEY,
    name        VARCHAR(80)  NOT NULL,
    description VARCHAR(255)
);

CREATE TABLE diet_type (
    code        VARCHAR(30) PRIMARY KEY,
    name        VARCHAR(80)  NOT NULL,
    description VARCHAR(255)
);

CREATE TABLE training_location (
    code VARCHAR(30) PRIMARY KEY,
    name VARCHAR(80) NOT NULL
);

-- Users
CREATE TABLE app_user (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email          VARCHAR(160) NOT NULL UNIQUE,
    password_hash  VARCHAR(100) NOT NULL,
    role           VARCHAR(10)  NOT NULL CHECK (role IN ('ADMIN', 'USER')),
    full_name      VARCHAR(120) NOT NULL,
    birth_date     DATE         NOT NULL,
    sex            VARCHAR(10)  NOT NULL CHECK (sex IN ('MALE', 'FEMALE', 'OTHER')),
    height_cm      INT          NOT NULL,
    weight_kg      DECIMAL(5,2) NOT NULL,
    activity_level VARCHAR(20)  NOT NULL,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- What the user wants for their healthy life
CREATE TABLE user_preference (
    user_id            BIGINT PRIMARY KEY REFERENCES app_user(id),
    goal_code          VARCHAR(30) NOT NULL REFERENCES goal(code),
    location_code      VARCHAR(30) NOT NULL REFERENCES training_location(code),
    days_per_week      INT         NOT NULL CHECK (days_per_week BETWEEN 1 AND 7),
    hours_per_day      DECIMAL(3,1) NOT NULL,
    diet_type_code     VARCHAR(30) NOT NULL REFERENCES diet_type(code),
    excluded_foods     VARCHAR(255)
);

-- Workout templates (managed by the admin)
CREATE TABLE workout_template (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_code     VARCHAR(30) NOT NULL REFERENCES goal(code),
    location_code VARCHAR(30) NOT NULL REFERENCES training_location(code),
    days_per_week INT         NOT NULL,
    name          VARCHAR(120) NOT NULL
);

CREATE TABLE workout_day (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id BIGINT NOT NULL REFERENCES workout_template(id),
    day_index   INT    NOT NULL,
    focus       VARCHAR(120) NOT NULL
);

CREATE TABLE workout_exercise (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    day_id   BIGINT NOT NULL REFERENCES workout_day(id),
    name     VARCHAR(120) NOT NULL,
    sets     INT NOT NULL,
    reps     VARCHAR(20) NOT NULL
);

-- Meal plans (managed by the admin)
CREATE TABLE meal_plan (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    goal_code      VARCHAR(30) NOT NULL REFERENCES goal(code),
    diet_type_code VARCHAR(30) NOT NULL REFERENCES diet_type(code),
    kcal_adjust    INT NOT NULL,           -- delta over TDEE (e.g. -500 to lose weight)
    name           VARCHAR(120) NOT NULL
);

CREATE TABLE meal (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_plan_id BIGINT NOT NULL REFERENCES meal_plan(id),
    meal_type    VARCHAR(20) NOT NULL,     -- BREAKFAST, LUNCH, DINNER, SNACK
    description  VARCHAR(255) NOT NULL,
    kcal         INT NOT NULL
);
